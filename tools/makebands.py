#!/usr/bin/env python3
"""Rebuild kenya/lead/bands.json from the test scripts themselves.

Run it from the repo root whenever a test script gains or loses steps:

    python3 tools/makebands.py            # write the file
    python3 tools/makebands.py --check    # say what would change, write nothing

Why this script exists. bands.json decides what every test pays, and until
8 November it was written by hand. On 6 November every script gained the same
two steps - watch this app's videos, read its store card - and the file was
never regenerated, so all 32 apps sat two steps short and 16 of them were a
whole band below where the rule put them. Nobody noticed for two days. A file
that claims to be generated has to actually be generated.

The boundaries. They are counted on the test script's own steps:

    up to 19  small     20-23  normal     24 or more  big

They used to read 14-17 / 18-21 / 22-30. They moved up by two on 8 November,
by Jerry's call, on the same day the undercount was found - because the two
steps every script gained are the same two steps in every script, so letting
them count would have shifted 16 apps up a band without any app's test
actually getting harder relative to the others. Rafiki is still a normal app
and The Key is still a small one, which is what both videos say out loud.

If a future change adds steps to SOME scripts and not others, that is a real
difference in the work and the boundaries should stay put.
"""
import json, glob, os, sys, datetime

SMALL_MAX, MEDIUM_MAX = 19, 23          # up to 19 small, 20-23 normal, 24 or more big
OUT = 'kenya/lead/bands.json'
RULE = ('Which app counts as which size. Counted from each app\'s own test script: '
        'up to 19 steps small, 20-23 normal, 24 or more big. Generated by tools/makebands.py from '
        'testers/scripts/*.json - run it again whenever a script gains or loses steps, '
        'and never edit this file by hand.')


def band(n):
    return 'small' if n <= SMALL_MAX else ('medium' if n <= MEDIUM_MAX else 'big')


def read_scripts():
    out = {}
    for path in sorted(glob.glob('testers/scripts/*.json')):
        key = os.path.basename(path)[:-5]
        with open(path, encoding='utf-8') as fh:
            doc = json.load(fh)
        # index.json and anything else without steps is not an app's script
        if not isinstance(doc, dict) or not isinstance(doc.get('steps'), list):
            continue
        n = len(doc['steps'])
        out[key] = {'steps': n, 'band': band(n), 'title': doc.get('name') or key}
    return out


def main():
    check = '--check' in sys.argv
    if not os.path.isdir('testers/scripts'):
        sys.exit('run this from the repo root - testers/scripts is not here')

    apps = read_scripts()
    if len(apps) < 20:
        sys.exit('only %d scripts found - that is too few to be right, writing nothing' % len(apps))

    old = {}
    if os.path.exists(OUT):
        with open(OUT, encoding='utf-8') as fh:
            old = json.load(fh).get('apps', {})

    changed = 0
    for key in sorted(set(old) | set(apps)):
        was, now = old.get(key), apps.get(key)
        if was == now:
            continue
        changed += 1
        if now is None:
            print('%-18s dropped (no script any more): was %s' % (key, was['band']))
        elif was is None:
            print('%-18s new: %d steps, %s' % (key, now['steps'], now['band']))
        else:
            flag = '  <-- BAND CHANGED' if was['band'] != now['band'] else ''
            print('%-18s %d steps %s  ->  %d steps %s%s'
                  % (key, was['steps'], was['band'], now['steps'], now['band'], flag))

    print('\n%d of %d rows differ' % (changed, len(apps)))
    for b in ('small', 'medium', 'big'):
        print('  %-6s %d' % (b, sum(1 for a in apps.values() if a['band'] == b)))

    if check:
        print('\n--check: nothing written')
        return

    doc = {'_': RULE,
           'generated': datetime.date.today().isoformat(),
           'apps': {k: apps[k] for k in sorted(apps)}}
    with open(OUT, 'w', encoding='utf-8') as fh:
        json.dump(doc, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    print('\nwrote ' + OUT)


if __name__ == '__main__':
    main()
