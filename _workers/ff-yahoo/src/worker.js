/* Daraja Studio · ff-yahoo · v1.0
   The small server half of Yahoo support for My Scores.

   Why this exists at all: ESPN and Sleeper can be read straight from the browser.
   Yahoo cannot, for two separate reasons, and neither has a client-side way round it.
     1. Yahoo needs an OAuth 2.0 bearer token. There is no cookie path like ESPN's,
        so being signed into Yahoo in the browser authorises nothing.
     2. Yahoo's API sends no CORS headers, so even holding a valid token, page
        JavaScript cannot read the response.
   Swapping an auth code for a token also needs the client secret, which can never
   sit in a file served from GitHub Pages. So: this Worker holds the secret, talks
   to Yahoo server-to-server, and hands the page back plain JSON it is allowed to read.

   What it deliberately does NOT do: store anything. No KV, no database, no user
   records. Tokens are handed to the browser and live only there, which keeps the
   Daraja promise that a user's data stays on their own device. The one thing this
   Worker knows is the client secret, and that is Daraja's, not the user's. */

const YAHOO_AUTH = "https://api.login.yahoo.com/oauth2/request_auth";
const YAHOO_TOKEN = "https://api.login.yahoo.com/oauth2/get_token";
const YAHOO_API = "https://fantasysports.yahooapis.com/fantasy/v2/";
const YAHOO_API_ORIGIN = "https://fantasysports.yahooapis.com";

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const origin = request.headers.get("Origin") || "";

    if (request.method === "OPTIONS") {
      return new Response(null, { status: 204, headers: cors(env, origin) });
    }

    // Every async handler below is awaited rather than just returned. `return fn()`
    // inside a try hands back the promise and leaves the try block, so a rejection
    // lands outside the catch and escapes as a raw runtime error — which is how a
    // message carrying the client secret could end up somewhere it shouldn't.
    try {
      if (url.pathname === "/login") return login(url, env);
      if (url.pathname === "/callback") return await callback(url, env);
      if (url.pathname === "/refresh") return await refresh(request, env, origin);
      if (url.pathname === "/health") return json({ ok: true, version: "1.0" }, 200, env, origin);
      if (url.pathname.startsWith("/api/")) return await proxy(request, url, env, origin);
      return json({ error: "not_found" }, 404, env, origin);
    } catch (err) {
      // Never let a stack trace or anything carrying the secret reach the browser.
      return json({ error: "worker_error" }, 500, env, origin);
    }
  }
};

/* ---------------------------- CORS ----------------------------
   The origin is echoed back only when it is one we configured, never "*".
   A wildcard is not allowed alongside credentials-bearing Authorization headers
   anyway, and echoing an unknown origin would let any page on the web drive this
   Worker with a user's token. APP_ORIGIN is a comma-separated list so a local
   dev origin can be added without code changes. */
function cors(env, origin) {
  const allowed = String(env.APP_ORIGIN || "").split(",").map(s => s.trim()).filter(Boolean);
  const headers = {
    "Vary": "Origin",
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Authorization, Content-Type",
    "Access-Control-Max-Age": "86400"
  };
  if (origin && allowed.includes(origin)) headers["Access-Control-Allow-Origin"] = origin;
  return headers;
}

function json(body, status, env, origin) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...cors(env, origin), "Content-Type": "application/json; charset=utf-8" }
  });
}

/* ---------------------------- /login ----------------------------
   Sends the user to Yahoo's consent screen.

   There is deliberately no "redirect back to" parameter. Accepting one would make
   this an open redirect that a phishing page could bounce through. The return
   address is whatever APP_RETURN_URL is configured as, and nothing else.

   `state` is generated by the page, kept in its sessionStorage, and checked when
   the user lands back. This Worker stores nothing, so it cannot verify state
   itself; it only carries it there and back. The format check below is just to
   keep junk out of the redirect. */
function login(url, env) {
  const state = url.searchParams.get("state") || "";
  if (!/^[A-Za-z0-9_-]{8,128}$/.test(state)) {
    return new Response("Bad or missing state parameter.", { status: 400 });
  }
  const auth = new URL(YAHOO_AUTH);
  auth.searchParams.set("client_id", env.YAHOO_CLIENT_ID);
  auth.searchParams.set("redirect_uri", env.REDIRECT_URI);
  auth.searchParams.set("response_type", "code");
  auth.searchParams.set("state", state);
  // No `scope` on purpose: Yahoo grants from the permissions the app is registered
  // with (Fantasy Sports Read), and sending a scope that doesn't match what the app
  // holds is a way to get rejected for no gain.
  return Response.redirect(auth.toString(), 302);
}

/* ---------------------------- /callback ----------------------------
   Yahoo sends the user here with a one-time code. We swap it for tokens server-side
   (that swap needs the secret) and then hand the tokens to the page in the URL
   fragment. The fragment is the right place: browsers never send it to a server, so
   the tokens do not appear in our logs, Cloudflare's, or anyone's in between. */
async function callback(url, env) {
  const back = new URL(env.APP_RETURN_URL);
  const fail = reason => {
    back.hash = "yh_error=" + encodeURIComponent(reason);
    return Response.redirect(back.toString(), 302);
  };

  const denied = url.searchParams.get("error");
  if (denied) return fail(denied);

  const code = url.searchParams.get("code");
  const state = url.searchParams.get("state") || "";
  if (!code) return fail("no_code");

  const tok = await exchange(env, {
    grant_type: "authorization_code",
    code,
    redirect_uri: env.REDIRECT_URI
  });
  if (!tok.ok) return fail(tok.error);

  back.hash = new URLSearchParams({
    yh_at: tok.data.access_token || "",
    yh_rt: tok.data.refresh_token || "",
    yh_exp: String(expiresAt(tok.data)),
    state
  }).toString();
  return Response.redirect(back.toString(), 302);
}

/* ---------------------------- /refresh ----------------------------
   Yahoo access tokens are short-lived (about an hour). The page sends back the
   refresh token it is holding and gets a fresh pair. This has to be here rather
   than in the page because refreshing needs the client secret too. */
async function refresh(request, env, origin) {
  if (request.method !== "POST") return json({ error: "method_not_allowed" }, 405, env, origin);

  let body = {};
  try { body = await request.json(); } catch (e) { /* handled by the check below */ }
  const rt = body && body.refresh_token;
  if (!rt || typeof rt !== "string") return json({ error: "missing_refresh_token" }, 400, env, origin);

  const tok = await exchange(env, {
    grant_type: "refresh_token",
    refresh_token: rt,
    redirect_uri: env.REDIRECT_URI
  });
  if (!tok.ok) return json({ error: tok.error }, 401, env, origin);

  return json({
    access_token: tok.data.access_token,
    // Yahoo may or may not rotate the refresh token. Keep the old one when it doesn't,
    // otherwise the page would throw away a token that still works.
    refresh_token: tok.data.refresh_token || rt,
    expires_at: expiresAt(tok.data)
  }, 200, env, origin);
}

/* The token endpoint, for both the first exchange and later refreshes.
   Credentials go in an HTTP Basic header, which is what OAuth 2.0 specifies for a
   confidential client and what the app is registered as. If Yahoo ever rejects that,
   the alternative is client_id and client_secret as form fields in the body — but
   send one or the other, never both, or the request is refused. */
async function exchange(env, params) {
  const res = await fetch(YAHOO_TOKEN, {
    method: "POST",
    headers: {
      "Authorization": "Basic " + btoa(env.YAHOO_CLIENT_ID + ":" + env.YAHOO_CLIENT_SECRET),
      "Content-Type": "application/x-www-form-urlencoded",
      "Accept": "application/json"
    },
    body: new URLSearchParams(params).toString()
  });

  const text = await res.text();
  let data = {};
  try { data = JSON.parse(text); } catch (e) { /* non-JSON means an error page; handled below */ }

  if (!res.ok) return { ok: false, error: String(data.error || "token_http_" + res.status) };
  if (!data.access_token) return { ok: false, error: "no_access_token" };
  return { ok: true, data };
}

function expiresAt(data) {
  const seconds = Number(data.expires_in);
  return Math.floor(Date.now() / 1000) + (Number.isFinite(seconds) && seconds > 0 ? seconds : 3600);
}

/* ---------------------------- /api/* ----------------------------
   A thin relay to Yahoo's fantasy v2 API. Everything after /api/ becomes the Yahoo
   resource path, the page's own bearer token rides along untouched, and the reply
   comes back with the CORS headers that let the page read it.

   Two things worth being careful about here:

   The target is pinned to Yahoo's host and checked again after the URL is built,
   so a crafted path can't turn this into a general-purpose proxy for any address.

   Nothing is cached Worker-side. Every response here is one user's private league
   data, and a shared cache is exactly how one user ends up seeing another's. The
   browser is told it may hold a copy privately for a short while, which is the safe
   way to keep call volume down — and Yahoo does throttle on volume. */
async function proxy(request, url, env, origin) {
  if (request.method !== "GET") return json({ error: "method_not_allowed" }, 405, env, origin);

  const auth = request.headers.get("Authorization") || "";
  if (!/^Bearer\s+\S+$/.test(auth)) return json({ error: "missing_bearer" }, 401, env, origin);

  let path = url.pathname.slice("/api/".length).replace(/^\/+/, "");
  try { path = decodeURIComponent(path); } catch (e) { return json({ error: "bad_path" }, 400, env, origin); }
  if (!path || path.includes("..")) return json({ error: "bad_path" }, 400, env, origin);

  let target;
  try { target = new URL(YAHOO_API + path); } catch (e) { return json({ error: "bad_path" }, 400, env, origin); }
  if (target.origin !== YAHOO_API_ORIGIN) return json({ error: "bad_path" }, 400, env, origin);
  if (!target.pathname.startsWith("/fantasy/v2/")) return json({ error: "bad_path" }, 400, env, origin);

  url.searchParams.forEach((value, key) => target.searchParams.set(key, value));
  target.searchParams.set("format", "json");   // Yahoo answers in XML unless asked otherwise

  const res = await fetch(target.toString(), {
    headers: { "Authorization": auth, "Accept": "application/json" }
  });
  const text = await res.text();

  // A 401 here means the access token aged out. Name it plainly so the page knows to
  // call /refresh and retry, rather than dumping the user back into a login loop.
  if (res.status === 401) return json({ error: "token_expired" }, 401, env, origin);
  if (!res.ok) return json({ error: "yahoo_http_" + res.status }, res.status, env, origin);

  return new Response(text, {
    status: 200,
    headers: {
      ...cors(env, origin),
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "private, max-age=30"
    }
  });
}
